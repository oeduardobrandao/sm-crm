// Builds the starter .fig templates minted by post-design-manage GET /blob when a post has
// no design yet. One preset frame per tipo, white fill, page named "Canvas".
// Run: cd scripts/estudio && npm i && node build-starter-figs.mjs
// Output: supabase/functions/post-design-manage/starter-templates.gen.ts (committed).
import { writeFile } from 'node:fs/promises'
import { BUILTIN_IO_FORMATS, IORegistry } from '@open-pencil/core/io'
import { computeAllLayouts } from '@open-pencil/core/layout'
import { SceneGraph } from '@open-pencil/core/scene-graph'

const io = new IORegistry(BUILTIN_IO_FORMATS)
// 4:5 is the product default for feed/carrossel (v1 decision, kept); reels covers are 9:16.
const SIZES = { feed: [1080, 1350], carrossel: [1080, 1350], reel_cover: [1080, 1920] }

const out = {}
for (const [kind, [w, h]] of Object.entries(SIZES)) {
  const graph = new SceneGraph()
  const page = graph.addPage('Canvas')
  graph.createNode('FRAME', page.id, {
    name: '1',
    x: 0,
    y: 0,
    width: w,
    height: h,
    fills: [{ type: 'SOLID', color: { r: 1, g: 1, b: 1, a: 1 }, opacity: 1, visible: true }]
  })
  computeAllLayouts(graph)
  const { data } = await io.writeDocument('fig', graph)
  out[kind] = Buffer.from(data).toString('base64')
  console.log(`${kind}: ${data.length} bytes`)
}

const ts = `// GENERATED by scripts/estudio/build-starter-figs.mjs — do not edit by hand.
// Starter .fig documents (one preset frame each) minted on first GET /blob of a design.
// Built with @open-pencil/core 0.13.2 — regenerate when the pinned editor version changes.

export const STARTER_TEMPLATES: Record<"feed" | "carrossel" | "reel_cover", string> = ${JSON.stringify(out, null, 2)};

export function starterTemplateFor(tipo: string): Uint8Array | null {
  const kind = tipo === "feed"
    ? "feed"
    : tipo === "carrossel"
      ? "carrossel"
      : tipo === "reels"
        ? "reel_cover"
        : null;
  if (!kind) return null;
  return Uint8Array.from(atob(STARTER_TEMPLATES[kind]), (c) => c.charCodeAt(0));
}
`
await writeFile('../../supabase/functions/post-design-manage/starter-templates.gen.ts', ts)
console.log('starter-templates.gen.ts written')

// sanity: round-trip each template through the reader
for (const [kind, b64] of Object.entries(out)) {
  const bytes = Uint8Array.from(Buffer.from(b64, 'base64'))
  const { graph } = await io.readDocument({ name: `${kind}.fig`, data: bytes })
  const canvas = graph.getPages().find((p) => p.name === 'Canvas')
  const frames = graph.getChildren(canvas.id).filter((n) => n.type === 'FRAME')
  if (frames.length !== 1 || frames[0].width !== SIZES[kind][0] || frames[0].height !== SIZES[kind][1]) {
    throw new Error(`${kind}: round-trip mismatch`)
  }
  console.log(`${kind}: round-trip OK (${frames[0].width}x${frames[0].height})`)
}
