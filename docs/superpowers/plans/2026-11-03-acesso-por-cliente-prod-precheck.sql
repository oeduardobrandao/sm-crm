tabelas_cliente as (
  select c.relname as t from pg_class c join pg_attribute a on a.attrelid = c.oid
   where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
     and a.attname = 'cliente_id' and not a.attisdropped
  union select unnest(array['clientes', 'membros', 'integracoes_status', 'instagram_post_tags',
    'analytics_reports', 'hub_pages', 'client_hub_tokens', 'portal_approvals', 'portal_tokens',
    'workflows', 'workflow_etapas', 'notifications', 'audit_log']))
select p.tablename, p.policyname, p.cmd
  from pg_policies p
 where p.schemaname = 'public'
   and p.permissive = 'PERMISSIVE'
   and p.tablename in (select t from tabelas_cliente)
   and not exists (select 1 from repo r where r.t = p.tablename and r.p = p.policyname)
 order by 1, 2;
